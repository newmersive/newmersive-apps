export function normalizeAppLocale(value: unknown): AppLocale | null {
  const language = String(value || "")
    .trim()
    .toLowerCase()
    .split(/[-_]/)[0];
  return APP_LOCALES.includes(language as AppLocale)
    ? (language as AppLocale)
    : null;
}

export function detectAppLocale(): AppLocale {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    return normalizeAppLocale(locale) || "es";
  } catch {
    return "es";
  }
}

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  replacements: Replacements = {},
) {
  const table =
    locale === "es" || locale === "en"
      ? resources[locale]
      : {
          ...supplementalResources[locale],
          ...featureResources[locale],
        };
  const template =
    table?.[key] ||
    (locale === "es" ? resources.es[key] : resources.en[key]) ||
    resources.es[key] ||
    key;
  return Object.entries(replacements).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template as string,
  );
}

export function getMissingTranslationKeys(locale: AppLocale): TranslationKey[] {
  if (locale === "es" || locale === "en") return [];
  const table: Partial<Record<TranslationKey, string>> = {
    ...supplementalResources[locale],
    ...featureResources[locale],
  };
  return (Object.keys(resources.es) as TranslationKey[]).filter(
    (key) => !String(table[key] || "").trim(),
  );
}

